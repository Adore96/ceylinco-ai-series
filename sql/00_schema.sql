-- =====================================================================
-- 00_schema.sql: the shared data model for Weeks 2 and 3 (8 tables)
-- =====================================================================
-- WHY one model: a claim created from a garage estimate in Week 2 is the
--      same claim a caller asks about in Week 3.
--
-- Fictional insurer: Lanka Shield Assurance (life and motor). All data
-- that goes into these tables is synthetic.
--
-- HOW TO RUN: SQL Workshop > SQL Scripts > Create. Paste this file. Run.
-- EXPECTED: "Statements processed: 16, successful: 16, with errors: 0".
-- TO START AGAIN: run sql/99_drop_schema.sql first.
--
-- Design notes (the WHY behind the choices):
-- * Surrogate keys are identity columns ("generated by default on null")
--   so seed scripts can insert fixed IDs and the app can leave them empty.
-- * Business numbers (policy_no, claim_no, reg_no, nic) are UNIQUE: callers
--   and documents quote these, never our internal IDs.
-- * CALLS uses the transcript ID ('CALL-001') as its key so demos can say
--   "call 1" and the row is easy to find.
-- * AI output columns are separate from human columns (triage_route is
--   the person's choice, ai_complaint_flag is the model's flag) so we can
--   compare them in SQL.
-- * Status and label columns have CHECK constraints: the AI can never
--   write a label we did not plan for.
-- * JSON columns use the native JSON type (Oracle AI Database 26ai).
-- * The embedding column is VECTOR(*, FLOAT32): any dimension count, so
--   the Gemini model choice (spike S6) does not lock the table.
--
-- Docs checked (19 Nov 2026), Oracle AI Database 26ai:
--   CREATE TABLE identity_clause; JSON data type; VECTOR data type
--   (AI Vector Search User's Guide).
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. Customers: one row per person who holds a policy.
-- ---------------------------------------------------------------------
create table customers (
    customer_id  number generated by default on null as identity
                 constraint customers_pk primary key,
    nic          varchar2(12)  not null
                 constraint customers_nic_uk unique,
    full_name    varchar2(100) not null,
    phone        varchar2(20),
    email        varchar2(100),
    city         varchar2(50),
    branch       varchar2(50)
);

-- ---------------------------------------------------------------------
-- 2. Policies: life and motor in one table; policy_type tells them apart.
-- ---------------------------------------------------------------------
create table policies (
    policy_id        number generated by default on null as identity
                     constraint policies_pk primary key,
    policy_no        varchar2(20)  not null
                     constraint policies_no_uk unique,
    customer_id      number        not null
                     constraint policies_customer_fk references customers,
    policy_type      varchar2(5)   not null
                     constraint policies_type_ck check ( policy_type in ('LIFE','MOTOR') ),
    product_name     varchar2(100) not null,
    sum_assured_lkr  number(14,2),
    premium_lkr      number(12,2)  not null,
    start_date       date          not null,
    end_date         date,
    status           varchar2(10)  default 'ACTIVE' not null
                     constraint policies_status_ck check ( status in ('ACTIVE','LAPSED','CANCELLED') )
);
create index policies_customer_ix on policies ( customer_id );

-- ---------------------------------------------------------------------
-- 3. Vehicles: each insured vehicle belongs to one motor policy.
-- ---------------------------------------------------------------------
create table vehicles (
    vehicle_id   number generated by default on null as identity
                 constraint vehicles_pk primary key,
    policy_id    number        not null
                 constraint vehicles_policy_fk references policies,
    reg_no       varchar2(15)  not null
                 constraint vehicles_reg_no_uk unique,   -- e.g. WP CAB-4521
    make         varchar2(30),
    model        varchar2(30),
    year         number(4),
    chassis_no   varchar2(30)
);
create index vehicles_policy_ix on vehicles ( policy_id );

-- ---------------------------------------------------------------------
-- 4. Estimates: garage estimate images and what the AI read from them.
--    Line items stay inside extracted_json and are read with JSON_TABLE.
-- ---------------------------------------------------------------------
create table estimates (
    estimate_id     number generated by default on null as identity
                    constraint estimates_pk primary key,
    file_name       varchar2(255) not null,
    mime_type       varchar2(100) not null,
    image           blob          not null,
    garage_name     varchar2(100),
    extracted_json  json,                       -- AI output (Week 2)
    model_score     number(3,2)
                    constraint estimates_score_ck check ( model_score between 0 and 1 ),
    check_results   json,                       -- SQL check output (Week 2)
    review_status   varchar2(12)
                    constraint estimates_review_ck
                    check ( review_status in ('AUTO_OK','NEEDS_REVIEW','APPROVED','REJECTED') ),
    reviewer        varchar2(255),
    claim_id        number,                     -- foreign key added below
    -- WHY "default on null": an APEX form sends an explicit NULL for an
    -- empty item, and a plain DEFAULT does not fire for an explicit NULL
    -- (found in the Week 2 rehearsal, 22 Nov: ORA-01400 on insert).
    created_on      timestamp with local time zone default on null systimestamp not null
);

-- ---------------------------------------------------------------------
-- 5. Claims: one row per claim on a policy.
-- ---------------------------------------------------------------------
create table claims (
    claim_id       number generated by default on null as identity
                   constraint claims_pk primary key,
    claim_no       varchar2(20)  not null
                   constraint claims_no_uk unique,      -- e.g. CLM-26-0004
    policy_id      number        not null
                   constraint claims_policy_fk references policies,
    vehicle_id     number
                   constraint claims_vehicle_fk references vehicles,
    incident_date  date          not null,
    claim_type     varchar2(30)  not null,              -- e.g. ACCIDENT, HOSPITAL
    status         varchar2(10)  default 'OPEN' not null
                   constraint claims_status_ck
                   check ( status in ('OPEN','ASSESSING','APPROVED','PAID','REJECTED') ),
    amount_lkr     number(14,2),
    estimate_id    number
                   constraint claims_estimate_fk references estimates
);
create index claims_policy_ix   on claims ( policy_id );
create index claims_vehicle_ix  on claims ( vehicle_id );
create index claims_estimate_ix on claims ( estimate_id );

-- WHY after CLAIMS: ESTIMATES and CLAIMS point at each other, so one of
-- the two foreign keys must be added once both tables exist.
alter table estimates add constraint estimates_claim_fk
    foreign key ( claim_id ) references claims;
create index estimates_claim_ix on estimates ( claim_id );

-- ---------------------------------------------------------------------
-- 6. Calls: call-centre transcripts, the human's routing, and AI output.
-- ---------------------------------------------------------------------
create table calls (
    call_id            varchar2(20)  constraint calls_pk primary key,   -- e.g. CALL-001
    customer_id        number
                       constraint calls_customer_fk references customers,
    call_time          timestamp with time zone not null,
    agent_name         varchar2(50),
    transcript         clob          not null,
    triage_route       varchar2(10)
                       constraint calls_route_ck check ( triage_route in ('BOT','SPECIALIST') ),
    ai_intent          varchar2(15)
                       constraint calls_intent_ck
                       check ( ai_intent in ('POLICY','CLAIM','PRODUCT_BRANCH','OTHER') ),
    ai_complaint_flag  varchar2(1)
                       constraint calls_flag_ck check ( ai_complaint_flag in ('Y','N') ),
    ai_reply           clob,
    reply_status       varchar2(11)
                       constraint calls_reply_ck check ( reply_status in ('AUTO_SENT','NEEDS_HUMAN') ),
    ai_summary         clob
);
create index calls_customer_ix on calls ( customer_id );

-- ---------------------------------------------------------------------
-- 7. Knowledge base documents (Week 3 RAG): product sheets, branches, FAQ.
-- ---------------------------------------------------------------------
create table kb_documents (
    doc_id    number generated by default on null as identity
              constraint kb_documents_pk primary key,
    title     varchar2(200) not null,
    doc_type  varchar2(10)  not null
              constraint kb_documents_type_ck
              check ( doc_type in ('PRODUCT','BRANCH','PROCESS','FAQ') ),
    body      clob          not null
);

-- ---------------------------------------------------------------------
-- 8. Knowledge base chunks: each document cut into pieces, with one
--    embedding per piece. Deleting a document deletes its chunks.
-- ---------------------------------------------------------------------
create table kb_chunks (
    chunk_id    number generated by default on null as identity
                constraint kb_chunks_pk primary key,
    doc_id      number not null
                constraint kb_chunks_doc_fk references kb_documents on delete cascade,
    chunk_no    number not null,
    chunk_text  clob   not null,
    embedding   vector(*, float32),
    constraint kb_chunks_doc_chunk_uk unique ( doc_id, chunk_no )
);
