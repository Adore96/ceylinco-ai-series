"""Write sql/week2/01_seed_data.sql from data/spec.py.

Usage: python data/make_seed_sql.py
WHY generated: the seed rows must match the estimate images and the call
transcripts exactly; spec.py is the one place those values live.
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).parent
sys.path.insert(0, str(HERE))
import spec  # noqa: E402

OUT = HERE.parent / "sql" / "week2" / "01_seed_data.sql"


def q(v):
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def d(v):
    return "null" if v is None else f"date '{v}'"


def main():
    problems, counts = spec.check_spec()
    assert not problems, problems
    cust = {c[0]: c for c in spec.CUSTOMERS}
    lines = []
    for i, (key, name, nic, city, branch) in enumerate(spec.CUSTOMERS):
        phone = f"070 000 {i + 1:04d}"   # 070 000 xxxx: obviously not a real number
        email = name.lower().replace(" ", ".") + "@example.com"   # reserved domain, never delivers
        lines.append(f"insert into customers (nic, full_name, phone, email, city, branch) values "
                     f"({q(nic)}, {q(name)}, {q(phone)}, {q(email)}, {q(city)}, {q(branch)});")
    for no, key, product, sa, prem, start, end, status in spec.POLICIES:
        ptype = "LIFE" if no.startswith("LSL") else "MOTOR"
        lines.append(
            "insert into policies (policy_no, customer_id, policy_type, product_name, sum_assured_lkr, premium_lkr, start_date, end_date, status) "
            f"values ({q(no)}, (select customer_id from customers where nic = {q(cust[key][2])}), {q(ptype)}, {q(product)}, "
            f"{q(sa)}, {q(prem)}, {d(start)}, {d(end)}, {q(status)});")
    for reg, pno, make, model, year, chassis in spec.VEHICLES:
        lines.append(
            "insert into vehicles (policy_id, reg_no, make, model, year, chassis_no) "
            f"values ((select policy_id from policies where policy_no = {q(pno)}), {q(reg)}, {q(make)}, {q(model)}, {year}, {q(chassis)});")
    for cno, pno, reg, incident, ctype, status, amount in spec.CLAIMS:
        veh = f"(select vehicle_id from vehicles where reg_no = {q(reg)})" if reg else "null"
        lines.append(
            "insert into claims (claim_no, policy_id, vehicle_id, incident_date, claim_type, status, amount_lkr) "
            f"values ({q(cno)}, (select policy_id from policies where policy_no = {q(pno)}), {veh}, {d(incident)}, {q(ctype)}, {q(status)}, {amount});")
    n = len(lines) + 1
    header = f"""-- =====================================================================
-- Week 2 / 01_seed_data.sql: customers, policies, vehicles and claims
-- =====================================================================
-- GENERATED by data/make_seed_sql.py from data/spec.py. Do not edit by
-- hand: change the spec and run the generator again.
--
-- WHY these rows: every policy, vehicle, claim and NIC that a call
-- transcript (data/calls/) or a garage estimate (data/estimates/) mentions
-- exists here, so the Week 2 checks and the Week 3 agent find real rows.
-- Claims CLM-26-0011 to 0013 are NOT here: they are created live in Week 2
-- from the estimates.
--
-- WHY subqueries instead of IDs: rows refer to each other by business
-- numbers (NIC, policy_no, reg_no), the same numbers callers quote. The
-- identity columns fill themselves.
--
-- HOW TO RUN: SQL Workshop > SQL Scripts > Create. Paste this file. Run.
-- Needs: sql/00_schema.sql first. To start again: sql/99_drop_schema.sql,
-- then 00_schema.sql, then this file.
-- EXPECTED: "Statements processed: {n}, successful: {n}, with errors: 0".
-- Rows: customers {counts['customers']}, policies {counts['life'] + counts['motor']} ({counts['life']} life, {counts['motor']} motor),
-- vehicles {counts['vehicles']}, claims {counts['claims']}.
--
-- All data is synthetic. Lanka Shield Assurance is fictional.
-- =====================================================================
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + "\n".join(lines) + "\ncommit;\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(HERE.parent)}: {n} statements")


if __name__ == "__main__":
    main()
